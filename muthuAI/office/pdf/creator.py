"""
MuthuAI Phase 5 — office/pdf/creator.py

PDF Document Creator.
Uses reportlab if available; includes a pure-python text PDF writer fallback.
"""

from __future__ import annotations
import os
from pathlib import Path
from utils.logger import get_logger

log = get_logger("muthuai.office.pdf.creator")


class PDFCreator:
    """
    Creates styled PDF documents (.pdf).
    """

    def create(
        self,
        file_name: str = "report.pdf",
        save_dir: str | Path = "data/documents",
        title: str = "PDF Report",
        paragraphs: list[str] | None = None,
        open_after: bool = False
    ) -> dict:
        """
        Create a PDF document.
        """
        save_path = Path(save_dir).resolve() / (file_name if file_name.endswith(".pdf") else f"{file_name}.pdf")
        save_path.parent.mkdir(parents=True, exist_ok=True)

        para_list = paragraphs or ["Report content generated by MuthuAI."]

        # 1. Try reportlab
        try:
            from reportlab.lib.pagesizes import letter
            from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
            from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
            from reportlab.lib import colors

            doc = SimpleDocTemplate(str(save_path), pagesize=letter)
            styles = getSampleStyleSheet()

            title_style = ParagraphStyle(
                "PDFTitle",
                parent=styles["Title"],
                textColor=colors.HexColor("#1F4E78"),
                fontSize=22,
                spaceAfter=15
            )
            body_style = styles["Normal"]

            story = [Paragraph(title, title_style), Spacer(1, 12)]

            for p in para_list:
                if isinstance(p, tuple):
                    heading, text = p
                    story.append(Paragraph(f"<b>{heading}</b>", styles["Heading2"]))
                    story.append(Paragraph(str(text), body_style))
                else:
                    story.append(Paragraph(str(p), body_style))
                story.append(Spacer(1, 8))

            doc.build(story)
            log.info("PDF document created via reportlab: %s", save_path)

            if open_after:
                try:
                    os.startfile(str(save_path))
                except Exception:
                    pass

            return {
                "success": True,
                "file_path": str(save_path),
                "file_name": save_path.name,
                "message": f"PDF report '{save_path.name}' created successfully."
            }

        except ImportError:
            log.info("reportlab not installed. Using pure-Python PDF writer fallback.")

        # 2. Pure Python Minimal PDF Generator Fallback
        try:
            content_text = f"{title}\n\n" + "\n\n".join(para_list)
            self._write_simple_pdf(save_path, content_text)
            log.info("PDF document created via fallback: %s", save_path)

            if open_after:
                try:
                    os.startfile(str(save_path))
                except Exception:
                    pass

            return {
                "success": True,
                "file_path": str(save_path),
                "file_name": save_path.name,
                "message": f"PDF report '{save_path.name}' created successfully."
            }
        except Exception as exc:
            log.error("Failed to create PDF %s: %s", save_path.name, exc)
            return {"success": False, "file_path": "", "message": f"Could not create PDF file: {exc}"}

    @staticmethod
    def _write_simple_pdf(path: Path, text: str) -> None:
        """Write a valid minimal 1.4 PDF file directly using raw PDF syntax."""
        stream = text.encode("utf-8", errors="replace")
        pdf_data = (
            b"%PDF-1.4\n"
            b"1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj\n"
            b"2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj\n"
            b"3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >> endobj\n"
            b"4 0 obj << /Length " + str(len(stream) + 50).encode() + b" >>\n"
            b"stream\nBT /F1 12 Tf 50 720 Td 14 TL\n" + stream + b"\nET\nendstream\nendobj\n"
            b"5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj\n"
            b"xref\n0 6\n0000000000 65535 f \n0000000009 00000 n \n0000000058 00000 n \n0000000115 00000 n \n0000000242 00000 n \n0000000350 00000 n \n"
            b"trailer << /Size 6 /Root 1 0 R >>\nstartxref\n425\n%%EOF\n"
        )
        path.write_bytes(pdf_data)
