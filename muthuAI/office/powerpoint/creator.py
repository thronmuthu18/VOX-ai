"""
MuthuAI Phase 5 — office/powerpoint/creator.py

PowerPoint Presentation (.pptx) Creator using python-pptx.
Creates multi-slide presentations with title slides, subheadings, and bullet points.
"""

from __future__ import annotations
import os
from pathlib import Path
from datetime import datetime
from utils.logger import get_logger

log = get_logger("muthuai.office.powerpoint.creator")


class PowerPointCreator:
    """
    Creates styled PowerPoint presentations (.pptx).
    """

    def create(
        self,
        file_name: str = "presentation.pptx",
        save_dir: str | Path = "data/documents",
        title: str = "Presentation Title",
        subtitle: str = "",
        slides: list[dict] | None = None,  # [{"title": str, "content": str, "bullets": [str]}, ...]
        open_after: bool = False
    ) -> dict:
        """
        Create a PowerPoint presentation (.pptx).
        slides format: [{"title": "Slide Title", "content": "Text paragraph...", "bullets": ["Point A", "Point B"]}, ...]
        """
        save_path = Path(save_dir).resolve() / (file_name if file_name.endswith(".pptx") else f"{file_name}.pptx")
        save_path.parent.mkdir(parents=True, exist_ok=True)

        slide_specs = slides or []

        try:
            from pptx import Presentation
            from pptx.util import Inches, Pt
            from pptx.enum.text import PP_ALIGN

            prs = Presentation()
            prs.slide_width = Inches(13.33)
            prs.slide_height = Inches(7.5)

            # Slide 1: Title Slide
            title_slide_layout = prs.slide_layouts[0]
            title_slide = prs.slides.add_slide(title_slide_layout)
            title_slide.shapes.title.text = title
            if len(title_slide.placeholders) > 1:
                sub = subtitle or f"Generated by MuthuAI — {datetime.now().strftime('%B %d, %Y')}"
                title_slide.placeholders[1].text = sub

            # Subsequent Content Slides
            content_layout = prs.slide_layouts[1]
            for s_data in slide_specs:
                slide = prs.slides.add_slide(content_layout)
                if isinstance(s_data, tuple):
                    slide_title, bullets = s_data
                    slide.shapes.title.text = str(slide_title)
                    body = slide.placeholders[1]
                    tf = body.text_frame
                    tf.clear()
                    if isinstance(bullets, list):
                        for idx, b in enumerate(bullets):
                            if idx == 0:
                                tf.text = str(b)
                            else:
                                p = tf.add_paragraph()
                                p.text = str(b)
                                p.level = 0
                    else:
                        tf.text = str(bullets)
                elif isinstance(s_data, dict):
                    slide_title = s_data.get("title", "Slide")
                    slide.shapes.title.text = slide_title
                    body = slide.placeholders[1]
                    tf = body.text_frame
                    tf.clear()
                    if s_data.get("content"):
                        tf.paragraphs[0].text = str(s_data["content"])
                    if s_data.get("bullets"):
                        bullets_list = s_data["bullets"] if isinstance(s_data["bullets"], list) else [s_data["bullets"]]
                        for idx, bullet_text in enumerate(bullets_list):
                            if not s_data.get("content") and idx == 0:
                                tf.paragraphs[0].text = str(bullet_text)
                            else:
                                p = tf.add_paragraph()
                                p.text = str(bullet_text)
                                p.level = 0 if not s_data.get("content") else 1

            prs.save(str(save_path))
            log.info("PowerPoint presentation created: %s (%d slides)", save_path, len(prs.slides))

            if open_after:
                try:
                    os.startfile(str(save_path))
                except Exception:
                    pass

            return {
                "success": True,
                "file_path": str(save_path),
                "file_name": save_path.name,
                "slide_count": len(prs.slides),
                "message": f"PowerPoint presentation '{save_path.name}' created successfully with {len(prs.slides)} slides."
            }

        except Exception as exc:
            log.error("Failed to create PowerPoint presentation %s: %s", save_path.name, exc)
            return {"success": False, "file_path": "", "message": f"Could not create PowerPoint presentation: {exc}"}
